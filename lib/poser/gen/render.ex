defmodule Poser.Gen.Render do
  @moduledoc """
  Renders a `Poser.Gen.Model` as Elixir source files and a JSON manifest.
  Output is formatted with `Code.format_string!/1`, so the same model always
  gives byte-identical files.
  """

  @doc "`{relative_path, source}` for every generated module."
  @spec files(map()) :: [{String.t(), iodata()}]
  def files(model) do
    header = header(model.meta)

    [model.functions | model.modules]
    |> Enum.map(fn mod -> {path(mod.module), format(module_source(mod, header))} end)
    |> Enum.sort()
  end

  @doc "The manifest as pretty JSON with sorted keys."
  @spec manifest_json(map()) :: iodata()
  def manifest_json(model), do: [pretty(model.manifest, ""), "\n"]

  defp path(module), do: Macro.underscore(module) <> ".ex"

  defp format(src), do: [Code.format_string!(src), "\n"]

  defp header(meta) do
    "Generated by `mix poser.gen` from `poser_api.json` " <>
      "(Poser #{meta["poser_version"]}, api_hash `#{String.slice(meta["api_hash"] || "", 0, 12)}`). Do not edit."
  end

  # --- modules ---

  defp module_source(mod, header) do
    methods? = Enum.any?(mod.funs, &(&1.kind == :method))

    title =
      if mod.py_class == "poser",
        do: "Module-level functions of PoserPython's `poser` module.",
        else: "PoserPython `#{mod.py_class}`."

    class_doc = Map.get(mod, :class_doc) || ""

    """
    defmodule #{inspect(mod.module)} do
      @moduledoc #{heredoc(Enum.join(Enum.reject([title, class_doc, header], &(&1 == "")), "\n\n"))}

      #{kernel_import(mod.kernel_except)}
      #{if methods?, do: "@accepts #{inspect(mod.accepts)}", else: ""}
      #{if Map.has_key?(mod, :accepts), do: "@type t :: Poser.Handle.t()", else: ""}

      #{if c = Map.get(mod, :constructor), do: fun_source(c, mod.py_class), else: ""}
      #{Enum.map_join(mod.funs, "\n\n", &fun_source(&1, mod.py_class))}
    end
    """
  end

  defp kernel_import([]), do: ""
  defp kernel_import(except), do: "import Kernel, except: #{inspect(except)}"

  # --- functions ---

  defp fun_source(fun, py_class) do
    where = if fun.kind == :method, do: "#{py_class}.#{fun.py_name}", else: "poser.#{fun.py_name}"
    note = if fun.note, do: "\n\nNote: #{fun.note}.", else: ""
    doc = "Python: `#{where}`#{note}\n\n#{String.trim(fun.doc)}"

    """
    @doc #{heredoc(doc)}
    @spec #{Macro.to_string(fun.spec)}
    #{def_source(fun)}
    """
  end

  defp def_source(%{source: :variadic} = fun) do
    case fun.kind do
      :method ->
        "def #{fun.name}(%Poser.Handle{class: c} = handle, args \\\\ [], opts \\\\ []) when c in @accepts and is_list(args), " <>
          "do: Poser.Call.method(handle, #{inspect(fun.py_name)}, args, [], opts)"

      :function ->
        "def #{fun.name}(args \\\\ [], opts \\\\ []) when is_list(args), " <>
          "do: Poser.Call.function(#{inspect(fun.py_name)}, args, [], opts)"
    end
  end

  defp def_source(fun) do
    vars = Enum.map(fun.required, &Atom.to_string(&1.var))
    args = "[" <> Enum.join(vars, ", ") <> "]"
    optional = inspect(fun.optional)

    case fun.kind do
      :method ->
        params = Enum.join(["%Poser.Handle{class: c} = handle" | vars] ++ ["opts \\\\ []"], ", ")

        "def #{fun.name}(#{params}) when c in @accepts, " <>
          "do: Poser.Call.method(handle, #{inspect(fun.py_name)}, #{args}, #{optional}, opts)"

      :function ->
        params = Enum.join(vars ++ ["opts \\\\ []"], ", ")

        "def #{fun.name}(#{params}), " <>
          "do: Poser.Call.function(#{inspect(fun.py_name)}, #{args}, #{optional}, opts)"
    end
  end

  # ~S heredoc: nothing is interpolated or unescaped except the closing
  # delimiter, which is written as \""" inside the text.
  defp heredoc(text) do
    body = text |> String.replace(~S("""), ~S(\""")) |> String.trim_trailing()
    ~s(~S"""\n) <> body <> ~s(\n""")
  end

  # --- JSON ---

  defp pretty(map, _indent) when is_map(map) and map_size(map) == 0, do: "{}"

  defp pretty(map, indent) when is_map(map) do
    inner = indent <> "  "

    items =
      map
      |> Enum.sort_by(fn {k, _} -> to_string(k) end)
      |> Enum.map(fn {k, v} -> [inner, JSON.encode!(to_string(k)), ": ", pretty(v, inner)] end)
      |> Enum.intersperse(",\n")

    ["{\n", items, "\n", indent, "}"]
  end

  defp pretty([], _indent), do: "[]"

  defp pretty(list, indent) when is_list(list) do
    inner = indent <> "  "
    items = list |> Enum.map(&[inner, pretty(&1, inner)]) |> Enum.intersperse(",\n")
    ["[\n", items, "\n", indent, "]"]
  end

  defp pretty(v, _indent), do: JSON.encode!(v)
end
