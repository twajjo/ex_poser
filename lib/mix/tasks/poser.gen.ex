defmodule Mix.Tasks.Poser.Gen do
  @shortdoc "Generates Poser.Api modules from priv/poser_api.json"
  @moduledoc """
  Generates one Elixir module per PoserPython class, the module-level
  functions, `Poser.Const`, and a coverage manifest.

      mix poser.gen [DUMP] [--out DIR] [--namespace MOD] [--manifest PATH]
                    [--overrides PATH] [--check]

  Defaults: `priv/poser_api.json`, `lib`, `Poser.Api`,
  `priv/poser_api_manifest.json`, `priv/poser_api_overrides.json`.

  `--check` writes nothing and fails if any generated file would change,
  is missing, or is no longer generated. Regenerate whenever Poser's
  `api_hash` changes, and fix problems in the overrides file, never in the
  generated files.
  """

  use Mix.Task

  alias Poser.Gen.{Model, Overrides, Render}

  @switches [
    out: :string,
    namespace: :string,
    manifest: :string,
    overrides: :string,
    check: :boolean
  ]

  @impl true
  def run(argv) do
    {opts, args} = OptionParser.parse!(argv, strict: @switches)
    dump_path = List.first(args, "priv/poser_api.json")
    out = Keyword.get(opts, :out, "lib")
    namespace = Module.concat([Keyword.get(opts, :namespace, "Poser.Api")])
    manifest = Keyword.get(opts, :manifest, "priv/poser_api_manifest.json")

    dump = dump_path |> File.read!() |> JSON.decode!()
    overrides = Overrides.load(Keyword.get(opts, :overrides, "priv/poser_api_overrides.json"))
    model = Model.build(dump, overrides, namespace)

    files =
      Enum.map(Render.files(model), fn {rel, src} ->
        {Path.join(out, rel), IO.iodata_to_binary(src)}
      end) ++
        [{manifest, IO.iodata_to_binary(Render.manifest_json(model))}]

    if opts[:check], do: check(files, out, namespace), else: write(files, out, namespace)
  end

  defp check(files, out, namespace) do
    changed = for {path, src} <- files, File.read(path) != {:ok, src}, do: path

    case changed ++ stale(files, out, namespace) do
      [] ->
        Mix.shell().info("poser.gen: generated files are up to date")

      paths ->
        Mix.raise("poser.gen: out of date, run `mix poser.gen`:\n  " <> Enum.join(paths, "\n  "))
    end
  end

  # Previously generated .ex files under the namespace's directory that this
  # run no longer generates. Only files carrying the generator's header
  # count, so hand-written code in the same directory is never touched.
  defp stale(files, out, namespace) do
    dir = Path.join(out, Macro.underscore(namespace))
    generated = MapSet.new(files, &elem(&1, 0))

    for path <- Path.wildcard(Path.join(dir, "*.ex")),
        path not in generated,
        File.read!(path) =~ "Generated by `mix poser.gen`",
        do: path
  end

  defp write(files, out, namespace) do
    for path <- stale(files, out, namespace), do: File.rm!(path)

    for {path, src} <- files do
      File.mkdir_p!(Path.dirname(path))
      File.write!(path, src)
    end

    Mix.shell().info("poser.gen: wrote #{length(files)} files")
  end
end
