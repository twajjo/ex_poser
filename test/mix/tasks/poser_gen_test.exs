defmodule Mix.Tasks.Poser.GenTest do
  use ExUnit.Case, async: true

  @moduletag :tmp_dir

  defp run(dir, extra) do
    Mix.Tasks.Poser.Gen.run(
      ["test/fixtures/gen_api.json", "--out", dir, "--namespace", "PoserTest.GenApiOut"] ++
        [
          "--manifest",
          Path.join(dir, "manifest.json"),
          "--overrides",
          "test/fixtures/gen_overrides.json"
        ] ++ extra
    )
  end

  test "writes the modules and the manifest, and --check passes on unchanged output", %{
    tmp_dir: dir
  } do
    ExUnit.CaptureIO.capture_io(fn -> run(dir, []) end)
    assert File.exists?(Path.join(dir, "poser_test/gen_api_out/actor_type.ex"))

    assert %{"summary" => %{"generated" => _}} =
             dir |> Path.join("manifest.json") |> File.read!() |> JSON.decode!()

    assert ExUnit.CaptureIO.capture_io(fn -> run(dir, ["--check"]) end) =~ "up to date"
  end

  test "--check fails on a changed, missing or stale file", %{tmp_dir: dir} do
    ExUnit.CaptureIO.capture_io(fn -> run(dir, []) end)
    File.write!(Path.join(dir, "poser_test/gen_api_out/actor_type.ex"), "edited")
    File.write!(Path.join(dir, "poser_test/gen_api_out/gone_type.ex"), "# Generated by `mix poser.gen` once\n")
    File.rm!(Path.join(dir, "manifest.json"))

    msg =
      assert_raise Mix.Error, fn ->
        ExUnit.CaptureIO.capture_io(fn -> run(dir, ["--check"]) end)
      end

    assert msg.message =~ "actor_type.ex"
    assert msg.message =~ "gone_type.ex"
    assert msg.message =~ "manifest.json"
  end

  test "files without the generated header are never deleted or reported", %{tmp_dir: dir} do
    hand = Path.join(dir, "poser_test/gen_api_out/hand_written.ex")
    File.mkdir_p!(Path.dirname(hand))
    File.write!(hand, "defmodule HandWritten do\nend\n")
    ExUnit.CaptureIO.capture_io(fn -> run(dir, []) end)
    assert File.exists?(hand)
    assert ExUnit.CaptureIO.capture_io(fn -> run(dir, ["--check"]) end) =~ "up to date"
  end
end
